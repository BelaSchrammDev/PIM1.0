using System.Collections.Generic;
using System.Linq;
using System.Text;
using ItemDataParser = IngameScript.Program.ItemDataParser;

namespace SmsItemDataGenerator
{
    /// <summary>
    /// Encodes the item data into the compact string format read by ItemDataParser.Parse
    /// (SMS1/Definitions/ItemDataParser.cs). Every encoding decision must be mirrored exactly by that parser.
    /// </summary>
    public static class ItemDataEncoder
    {
        public static string EncodeMod(ModItemData mod)
        {
            var entries = new List<string>();
            foreach (var section in mod.Sections.Where(s => s.Rows.Count > 0))
            {
                var defaultMax = DefaultMax(section);
                entries.Add("#" + ItemDataParser.TypeCodes[System.Array.IndexOf(ItemDataParser.TypeNames, section.Type)]
                    + defaultMax + (section.Category != "" ? ":" + section.Category : ""));
                foreach (var row in section.Rows)
                {
                    var fields = row.Fields.ToArray();
                    // the max fields (resource: ore and ingot max) are left out if they are the default of the section
                    foreach (var i in MaxFieldIndexes(section))
                    {
                        var max = int.Parse(fields[i]);
                        fields[i] = max == defaultMax ? "" : max.ToString();
                    }
                    var count = fields.Length;
                    while (count > 1 && fields[count - 1] == "") count--;
                    entries.Add(string.Join(":", fields, 0, count));
                }
            }
            return string.Join(",", entries);
        }

        static int[] MaxFieldIndexes(ItemSection section) => section.IsResource ? new[] { 1, 2 } : new[] { 1 };

        // the most frequent max of the section (ties: the one used first), so most entries need no max
        static int DefaultMax(ItemSection section)
        {
            var values = section.Rows.SelectMany(r => MaxFieldIndexes(section).Select(i => int.Parse(r.Fields[i]))).ToList();
            return values.GroupBy(v => v).OrderByDescending(g => g.Count()).ThenBy(g => values.IndexOf(g.Key)).First().Key;
        }

        public static string GenerateSource(List<ModItemData> mods)
        {
            var sb = new StringBuilder();
            sb.Append("// <auto-generated>\n");
            sb.Append("// Generated by SMS1.ItemDataGenerator from SMS1/ItemData/*.txt. Do not edit,\n");
            sb.Append("// change the data files instead. Format: see Definitions/ItemDataParser.cs\n");
            sb.Append("// </auto-generated>\n");
            sb.Append("namespace IngameScript\n{\n    partial class Program\n    {\n");
            sb.Append("        // load order; Vanilla is always loaded, the other names are the mod keys of the config\n");
            sb.Append("        public static readonly string[] ItemDataMods =\n        {\n");
            foreach (var mod in mods) sb.Append("            \"").Append(mod.Name).Append("\",\n");
            sb.Append("        };\n\n");
            sb.Append("        public static readonly string[] ItemData =\n        {\n");
            foreach (var mod in mods)
            {
                sb.Append("            // ").Append(mod.Name).Append('\n');
                sb.Append("            \"").Append(EncodeMod(mod)).Append("\",\n");
            }
            sb.Append("        };\n    }\n}\n");
            return sb.ToString();
        }
    }
}
